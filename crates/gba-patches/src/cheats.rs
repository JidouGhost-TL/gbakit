/// Metadata for a clean-room verified classic in-game button-combo cheat.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct ButtonComboCheat {
    pub game_code: &'static str,
    pub aliases: &'static [&'static str],
    pub release_key: &'static str,
    pub display_name: &'static str,
    pub effect: &'static str,
    pub sequence: &'static [&'static str],
    pub memory_address: &'static str,
    pub activation_indicator: &'static str,
    pub wave: u8,
}

impl ButtonComboCheat {
    /// Formatted comma-separated sequence string.
    pub fn sequence_str(&self) -> String {
        self.sequence.join(", ")
    }

    /// Check if this cheat matches the given 4-character game code or alias.
    pub fn matches_code(&self, code: &str) -> bool {
        let upper = code.to_ascii_uppercase();
        self.game_code == upper || self.aliases.iter().any(|a| a.eq_ignore_ascii_case(code))
    }
}

